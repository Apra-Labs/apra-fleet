#!/usr/bin/env node
/**
 * build-sea.mjs — esbuild CJS bundle for Node.js SEA
 *
 * Bundles src/ into a single dist/sea-bundle.cjs with:
 * - BUILD_VERSION injected at compile time
 * - import.meta.url shimmed for CJS compat
 * - ssh2's cpu-features native addon marked external
 */

import { build } from 'esbuild';
import { readFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

// Read version
const versionFile = JSON.parse(readFileSync(join(root, 'version.json'), 'utf-8'));
let gitHash = '';
try {
  // First 6 chars of the full SHA (never a longer disambiguated abbreviation):
  // the prerelease tag and src/version.ts use the same rule.
  gitHash = execSync('git rev-parse HEAD', { cwd: root, encoding: 'utf-8', windowsHide: true }).trim().slice(0, 6);
} catch { /* no git */ }
const version = gitHash ? `v${versionFile.version}_${gitHash}` : `v${versionFile.version}`;

console.log(`Building SEA bundle — version: ${version}`);

await build({
  entryPoints: [join(root, 'src', 'index.ts')],
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'cjs',
  outfile: join(root, 'dist', 'sea-bundle.cjs'),
  sourcemap: false,
  minify: false, // keep readable for debugging
  // Inject BUILD_VERSION at compile time; shim import.meta.url → CJS equivalent
  define: {
    'BUILD_VERSION': JSON.stringify(version),
    'import.meta.url': 'import_meta_url',
  },
  banner: {
    js: [
      '// Node.js SEA bundle — generated by build-sea.mjs',
      'var import_meta_url = typeof document === "undefined" ? require("url").pathToFileURL(__filename).href : undefined;',
    ].join('\n'),
  },
  // ssh2's optional native addon — safe to externalize because ssh2 wraps
  // require('cpu-features') in try/catch (lib/protocol/constants.js:6-8)
  external: ['cpu-features'],
  loader: { '.node': 'empty' },
  // Log size
  metafile: true,
});

console.log(`Bundle written to dist/sea-bundle.cjs`);

// KB embed worker: the model loads and runs in a worker_thread (see
// src/services/knowledge/embedding/worker-runtime.ts). A SEA has no script
// file to hand new Worker(), so the worker is bundled on its own into a
// self-contained CommonJS script that gen-sea-config.mjs embeds as the SEA
// asset 'kb/embed-worker.cjs' (EMBED_WORKER_SEA_ASSET) and worker-runtime.ts
// runs with eval. The same file next to sea-bundle.cjs serves a plain-Node run
// of the bundle. The banner must match EMBED_WORKER_BANNER in worker-runtime.ts.
await build({
  entryPoints: [join(root, 'src', 'services', 'knowledge', 'embedding', 'embed-worker.ts')],
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'cjs',
  outfile: join(root, 'dist', 'kb-embed-worker.cjs'),
  sourcemap: false,
  minify: false,
  define: { 'import.meta.url': 'import_meta_url' },
  banner: {
    js: 'var import_meta_url = (typeof __filename === "string" && require("path").isAbsolute(__filename)) '
      + '? require("url").pathToFileURL(__filename).href : "file:///kb-embed-worker.cjs";',
  },
  loader: { '.node': 'empty' },
});

console.log('KB embed worker written to dist/kb-embed-worker.cjs');
