interface TaxonomyDoc {
  groups: Record<string, { codes: Array<{ code: string; source?: string }> }>;
}

interface Citation {
  file: string;
  startLine: number;
  endLine: number;
}

/**
 * Parse every file:line (and file:line-line) sub-citation out of a taxonomy
 * "source" string, handling the two multi-citation shapes actually used in
 * taxonomy.json:
 *  - continuations that omit the file ("sqlite-provider.ts:1545 (promote),
 *    :1744 (feedback)") -- inherit the most recently seen file;
 *  - a parenthetical annotation that itself may contain one nested paren pair
 *    and commas ("(assertCheckableBasis, KbCaptureRejected('x'))") -- must
 *    NOT be mistaken for a citation separator.
 *
 * Previous bug (pre-rewrite): the old regex required a bare `<name>.ts`
 * immediately before every colon, so continuation citations without a
 * restated filename were silently dropped (never checked), and it had no
 * paren-awareness at all.
 */
// A couple of taxonomy.json citations name a file WITHOUT its directory
// (e.g. "...at sqlite-provider.ts:1683" rather than the full
// "src/services/knowledge/sqlite-provider.ts:1683" every other citation of
// the same file uses). Canonicalized here rather than in taxonomy.json --
// that bare form was already verified correct by the citation refresh pass
// (my-beads-db-qy8.10.1) and is not part of what this guard was asked to
// rewrite.
const FILE_ALIASES: Record<string, string> = {
  'sqlite-provider.ts': 'src/services/knowledge/sqlite-provider.ts',
};

function extractCitations(source: string): Citation[] {
  const citations: Citation[] = [];
  let currentFile: string | undefined;
  const re = /([\w./-]+\.ts)?:(\d+)(?:-(\d+))?(?:\s*\(((?:[^()]|\([^()]*\))*)\))?/g;
  for (const m of source.matchAll(re)) {
    const [, file, startStr, endStr] = m;
    if (file) currentFile = file.includes('/') ? file : (FILE_ALIASES[file] ?? file);
    if (!currentFile) continue; // defensive; every real citation has a file eventually
    const startLine = parseInt(startStr, 10);
    const endLine = endStr ? parseInt(endStr, 10) : startLine;
    citations.push({ file: currentFile, startLine, endLine });
  }
  return citations;
}

