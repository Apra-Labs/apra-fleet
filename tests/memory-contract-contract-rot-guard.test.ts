// [test] Guard memory-contract source citations, tool counts and bead-id-free prose
// against silent rot (my-beads-db-qy8.10.2)
//
// This test guards against three classes of silent drift that have recurred
// (and that an earlier version of this very guard failed to actually catch --
// see the per-guard design notes below for what changed and why):
//
// 1. Citation rot: every file:line citation under taxonomy.json's
//    groups[].codes[].source resolves to the construct it claims. Resolution
//    is TOKEN-based: each citation is checked against an explicit, hand
//    verified expected substring (not a generic "is the line non-blank"
//    check, which cannot tell a correct citation from one that drifted a few
//    lines into unrelated code -- that was GUARD 1's bug before this rewrite).
//
//    SCOPE: only groups[].codes[].source citations are checked. taxonomy.json
//    also carries file references in non_error_outcomes[].where and
//    excluded_from_closed_set.codes[].where, but those use a different field
//    shape (some name files with no line number at all, e.g.
//    N-ANCHOR-VERBATIM-MISSING) and were not part of what this lane's citation
//    refresh (my-beads-db-qy8.10.1) or the reviewer's falsifiability probes
//    touched. Narrowing to groups[].codes[].source keeps every citation this
//    guard checks backed by a verified, explicit token.
//
// 2. Count drift: live prose about the kb_*/code_* tool count must be
//    self-consistent with the REAL registered count, read directly off
//    src/services/tool-registry.ts (the actual registry, not another copy of
//    the prose -- generate-contract.mjs's KB_MODULES/CODE_EXPORTS lists were
//    the previous guard's source and that is exactly how it validated prose
//    against prose instead of against the registry).
//
// 3. Bead ids in shipped prose: contract artifacts under memory-contract/v1
//    must not contain tracker bead IDs outside code comments. This guard
//    scans the WHOLE memory-contract/v1 tree (a directory walk, not a
//    hardcoded file list -- the earlier version's hardcoded 7-file list is
//    why README.md and INVARIANTS-UNHOMED-DRAFT.md went unpoliced) and
//    matches both tracker id families seen in this repo's history
//    (`my-beads-db-...` and the hash-like `apra-fleet-...` shape named in
//    CLAUDE.md), while not false-positiving on ordinary compound names like
//    `apra-fleet-client`/`apra-fleet-workflow` (those carry no digit in the
//    segment right after the dash; real ids do -- 23c, b4g.4, 0cd.14, ...).
//
// EXCLUSIONS: The following are deliberately point-in-time transcripts and are
// skipped BY NAME (visible here, not implied by a path convention):
// - memory-contract/v1/SIGNOFF.md (final audit snapshot)
// - memory-contract/v1/tests/DRIFT-GUARD-DRYRUN.md (example output)
// - memory-contract/v1/T2A-COMPLETION-REPORT.md (final report)
//
// INVENTORY.md carries two DELIBERATE historical sentences (section 1 and
// section 6) stating the original pre-kb_demote count was 23 (16 kb_* + 7
// code_*) -- that is correct history, not drift, and is allow-listed by exact
// sentence text below (an anchored, justified exception, per the lane's
// re-planning correction) rather than by excluding the whole file, which
// would also blind GUARD 3 on the very file the bead-id rule most needs to
// police.
//
// docs/sprint-analysis-*.md files are per-sprint, hash-suffixed historical
// snapshots generated by the harvester after a sprint closes (see CLAUDE.md's
// "pre-computed cost analysis block"); they are never revisited once written,
// the same deliberate-transcript shape as the three named exclusions above,
// so they are skipped by filename pattern rather than enumerated individually.

import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, it, expect } from 'vitest';

const REPO_ROOT = fileURLToPath(new URL('..', import.meta.url));
const MEMORY_CONTRACT_DIR = path.join(REPO_ROOT, 'memory-contract', 'v1');
const DOCS_DIR = path.join(REPO_ROOT, 'docs');

// ---------------------------------------------------------------------------
// Shared: recursive file walk, relative-path based (stable across OSes).
// ---------------------------------------------------------------------------

function walkFiles(baseDir: string): string[] {
  const out: string[] = [];
  const recurse = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        recurse(full);
      } else if (entry.isFile()) {
        out.push(path.relative(baseDir, full));
      }
    }
  };
  recurse(baseDir);
  return out;
}

