/** Resolve a citation: file must exist, range in bounds, token present somewhere in range. */
function resolveCitation(cite: Citation, expectedToken: string): { ok: boolean; error?: string } {
  const fullPath = path.join(REPO_ROOT, cite.file);
  let content: string;
  try {
    content = readFileSync(fullPath, 'utf8');
  } catch {
    return { ok: false, error: `File not found: ${cite.file}` };
  }

  const lines = content.split('\n');
  if (cite.startLine - 1 >= lines.length || cite.startLine < 1) {
    return { ok: false, error: `Line ${cite.startLine} out of range (file has ${lines.length} lines)` };
  }

  for (let line = cite.startLine; line <= cite.endLine; line++) {
    const text = lines[line - 1];
    if (text !== undefined && text.includes(expectedToken)) {
      return { ok: true };
    }
  }
  return {
    ok: false,
    error: `Expected token ${JSON.stringify(expectedToken)} not found in ${cite.file}:${cite.startLine}${cite.endLine !== cite.startLine ? `-${cite.endLine}` : ''}`,
  };
}

function readJsonDoc(filename: string): unknown {
  return JSON.parse(readFileSync(path.join(MEMORY_CONTRACT_DIR, filename), 'utf8'));
}

describe('memory-contract rot guard: GUARD 1 -- citation rot', () => {
  it('every taxonomy.json groups[].codes[].source citation resolves to its expected token', () => {
    const taxonomy = readJsonDoc('taxonomy.json') as TaxonomyDoc;
    const errors: string[] = [];

    for (const [groupName, group] of Object.entries(taxonomy.groups)) {
      for (const code of group.codes) {
        if (!code.source) {
          errors.push(`${code.code}: no source citation`);
          continue;
        }
        const citations = extractCitations(code.source);
        if (citations.length === 0) {
          errors.push(`${code.code} (${groupName}): no citation could be parsed from "${code.source}"`);
          continue;
        }
        for (const cite of citations) {
          const key = `${cite.file}:${cite.startLine}`;
          const expectedToken = EXPECTED_TOKENS[key];
          if (expectedToken === undefined) {
            errors.push(
              `${code.code} (${groupName}): ${key} has no entry in EXPECTED_TOKENS -- ` +
              `add one (this guard refuses to pass a citation it has never actually checked)`,
            );
            continue;
          }
          const resolved = resolveCitation(cite, expectedToken);
          if (!resolved.ok) {
            errors.push(`${code.code} (${groupName}): ${key} -> ${resolved.error}`);
          }
        }
      }
    }

    if (errors.length > 0) {
      throw new Error(`Citation rot detected:\n${errors.join('\n')}`);
    }
  });

  // Falsifiability: directly reproduce the reviewer's probe (shifting
  // E-DEMOTE-SUPERSEDED's citation from :1654 to :1658 produced NO error
  // under the old guard) against the REAL on-disk file, with no mutation.
  it('resolveCitation fails when a real citation is shifted a few lines, and passes at the true location', () => {
    const real: Citation = { file: 'src/services/knowledge/sqlite-provider.ts', startLine: 1654, endLine: 1654 };
    expect(resolveCitation(real, 'Cannot demote superseded').ok).toBe(true);

    const shifted: Citation = { ...real, startLine: 1658, endLine: 1658 };
    const shiftedResult = resolveCitation(shifted, 'Cannot demote superseded');
    expect(shiftedResult.ok).toBe(false);
  });

  // Second falsifiability case, reproducing the E-NO-BASIS staleness class
  // this lane fixed (citation off by ~50 lines, landing inside an unrelated
  // method).
  it('resolveCitation fails when a citation drifts ~50 lines into an unrelated construct', () => {
    const real: Citation = { file: 'src/services/knowledge/sqlite-provider.ts', startLine: 394, endLine: 394 };
    expect(resolveCitation(real, 'no_source_files').ok).toBe(true);

    const driftedToOldStaleCitation: Citation = { ...real, startLine: 339, endLine: 339 };
    expect(resolveCitation(driftedToOldStaleCitation, 'no_source_files').ok).toBe(false);
  });

  it('extractCitations parses continuation citations (no restated filename) and paren-nested annotations', () => {
    const multi = extractCitations(
      "src/services/knowledge/sqlite-provider.ts:1545 (promote), :1744 (feedback), :1651 (demote)",
    );
    expect(multi).toEqual([
      { file: 'src/services/knowledge/sqlite-provider.ts', startLine: 1545, endLine: 1545 },
      { file: 'src/services/knowledge/sqlite-provider.ts', startLine: 1744, endLine: 1744 },
      { file: 'src/services/knowledge/sqlite-provider.ts', startLine: 1651, endLine: 1651 },
    ]);

    const nestedParenAnnotation = extractCitations(
      "src/services/knowledge/sqlite-provider.ts:348 (unresolvableBasisFiles), :404 (assertCheckableBasis, KbCaptureRejected('missing_source_files'))",
    );
    expect(nestedParenAnnotation).toEqual([
      { file: 'src/services/knowledge/sqlite-provider.ts', startLine: 348, endLine: 348 },
      { file: 'src/services/knowledge/sqlite-provider.ts', startLine: 404, endLine: 404 },
    ]);

    const crossFileWithSemicolon = extractCitations(
      'src/services/knowledge/path-validation.ts:6 (absolute), :10 (traversal); demote evidence_files check at sqlite-provider.ts:1683',
    );
    expect(crossFileWithSemicolon).toEqual([
      { file: 'src/services/knowledge/path-validation.ts', startLine: 6, endLine: 6 },
      { file: 'src/services/knowledge/path-validation.ts', startLine: 10, endLine: 10 },
      { file: 'src/services/knowledge/sqlite-provider.ts', startLine: 1683, endLine: 1683 },
    ]);
  });
});

